import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(await readFile(join(root, "official-xzqh-2025.json"), "utf8"));

if (source.data?.level !== 0 || !Array.isArray(source.data.children)) {
  throw new Error("Unexpected official data format");
}

const counts = { province: 0, prefecture: 0, county: 0 };
const seen = new Set();

function convert(item) {
  if (![1, 2, 3].includes(item.level) || typeof item.name !== "string") {
    throw new Error(`Invalid division: ${JSON.stringify(item)}`);
  }
  if (!Array.isArray(item.children) && item.children !== null) {
    throw new Error(`Invalid children for ${item.name}`);
  }
  if (item.code !== "资料暂缺" && !/^\d{2}(\d{2})?(\d{2})?$/.test(item.code)) {
    throw new Error(`Invalid code for ${item.name}: ${item.code}`);
  }
  const code = item.code === "资料暂缺" ? null : item.code.padEnd(6, "0");
  if (code && seen.has(code)) throw new Error(`Duplicate code: ${code}`);
  if (code) seen.add(code);

  counts[["", "province", "prefecture", "county"][item.level]]++;
  const children = (item.children || []).map(convert);
  children.sort((a, b) => (a.code || "999999").localeCompare(b.code || "999999"));
  return { code, name: item.name, type: item.type, level: item.level, children };
}

const divisions = source.data.children.map(convert);
divisions.sort((a, b) => (a.code || "999999").localeCompare(b.code || "999999"));

if (counts.province !== 34 || counts.prefecture < 300 || counts.county < 2800) {
  throw new Error(`Incomplete official data: ${JSON.stringify(counts)}`);
}

const output = {
  asOf: "2025-12-31",
  source: "https://dmfw.mca.gov.cn/XzqhVersionPublish.html",
  counts,
  divisions,
};
await writeFile(
  join(root, "public", "divisions.js"),
  `/* Generated by scripts/build-data.mjs from official-xzqh-2025.json. */\nwindow.DIVISIONS_DATA = ${JSON.stringify(output)};\n`,
);
console.log(`Generated divisions.js: ${JSON.stringify(counts)}`);
